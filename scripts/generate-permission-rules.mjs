import { readFile, writeFile } from 'node:fs/promises';
import { PHOTO_FIELDS, METRIC_FIELDS, COVERAGE_FIELDS } from '../src/security/readModels.mjs';
const catalog = JSON.parse(await readFile(new URL('../src/security/catalog.json', import.meta.url)));
const roles = JSON.parse(await readFile(new URL('../src/security/roleDefaults.json', import.meta.url)));
const list = value => JSON.stringify(value);
const ids = catalog.map(p => p.id);
const dependents = {};
for (const entry of catalog) for (const dep of entry.requires) (dependents[dep] ||= []).push(entry.id);
const dependencyChecks = Object.entries(dependents).map(([dep, requiring]) => `(!permissions.hasAny(${list(requiring)}) || '${dep}' in permissions)`).join('\n        && ');
const approvalFields = ['status', 'approvedAt', 'approvedById', 'itoApprovalDate', 'itoApproverName', 'itoComments', 'itoSignatureDataUrl'];
const trace = ['updatedById', 'updatedByName', 'updatedAt', 'revision'];
const rules = `// Generated by scripts/generate-permission-rules.mjs. Edit the generator/catalog.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function signedIn() { return request.auth != null; }
    function memberPath() { return /databases/$(database)/documents/users/$(request.auth.uid); }
    function member() { return get(memberPath()).data; }
    function active() { return signedIn() && exists(memberPath()) && member().active == true; }
    function principal() { return active() && member().role == 'SUPER_ADMIN'; }
    function defaults(role) { return ${Object.entries(roles).map(([role, permissions]) => `role == '${role}' ? ${JSON.stringify(permissions)} : `).join('')} []; }
    function permissionsOf(data) { return 'permissions' in data ? data.permissions : defaults(data.get('role', '')); }
    function can(id) {
      let profile = member();
      return signedIn() && profile.active == true && (profile.role == 'SUPER_ADMIN'
        || (id != 'maintenance.reset' && id in permissionsOf(profile)));
    }
    function tenant(data) { let profile = member(); return signedIn() && profile.active == true && data.tenantId == profile.tenantId; }
    function contract(data) { return member().get('accessScope', 'TENANT') != 'CONTRACT' || data.get('contractId', '') == member().get('contractId', '__none__'); }
    function area(data) { return member().get('allowedAreaIds', []).size() == 0 || data.get('areaId', '') in member().allowedAreaIds; }
    function scoped(data) {
      let profile = member();
      return signedIn() && profile.active == true && data.tenantId == profile.tenantId
        && (profile.get('accessScope', 'TENANT') != 'CONTRACT' || data.get('contractId', '') == profile.get('contractId', '__none__'))
        && (profile.get('allowedAreaIds', []).size() == 0 || data.get('areaId', '') in profile.allowedAreaIds);
    }
    function payload(data) { return data.get('payload', data); }
    function validPermissions(permissions) {
      return permissions is list && permissions.size() <= ${ids.length} && permissions.hasOnly(${list(ids)})
        && ${dependencyChecks};
    }
    function mayGrant(data) {
      let permissions = permissionsOf(data);
      return validPermissions(permissions)
        && (!('maintenance.reset' in permissions) || data.get('role','') == 'SUPER_ADMIN')
        && (principal() || (data.role != 'SUPER_ADMIN' && !('maintenance.reset' in permissions) && permissionsOf(member()).hasAll(permissions)))
        && (member().get('accessScope', 'TENANT') != 'CONTRACT' || (data.get('accessScope', 'TENANT') == 'CONTRACT' && data.contractId == member().contractId))
        && (member().get('allowedAreaIds', []).size() == 0 || (data.get('allowedAreaIds', []).size() > 0 && member().allowedAreaIds.hasAll(data.allowedAreaIds)));
    }
    function validUser(data, uid) {
      return data.id == uid && data.name is string && data.email is string && data.active is bool
        && data.role in ${list(Object.keys(roles))}
        && data.get('accessScope', 'TENANT') in ['TENANT', 'CONTRACT']
        && (data.get('accessScope', 'TENANT') != 'CONTRACT' || (data.contractId is string && data.contractId.size() > 0))
        && data.get('allowedAreaIds', []) is list && data.get('allowedAreaIds', []).size() <= 10
        && !('password' in data) && !('password' in data.get('payload', {}))
        && data.diff(data.payload).affectedKeys().hasOnly(['payload', 'updatedAt']);
    }
    function userUpdateAllowed(previous, next, uid) {
      let actor = member();
      let grants = actor.role == 'SUPER_ADMIN' ? defaults('SUPER_ADMIN') : permissionsOf(actor);
      let rootChanges = next.diff(previous).affectedKeys();
      let profileChanges = payload(next).diff(payload(previous)).affectedKeys();
      return request.auth.uid == uid || previous.role == 'SUPER_ADMIN'
        ? 'users.edit' in grants && rootChanges.hasOnly(['name','payload','updatedAt']) && profileChanges.hasOnly(['name'])
        : (next.name == previous.name || 'users.edit' in grants)
          && (next.active == previous.active || 'users.disable' in grants)
          && (rootChanges.hasOnly(['name','active','payload','updatedAt']) && profileChanges.hasOnly(['name','active'])
            || 'access.manage' in grants && mayGrant(next));
    }
    match /users/{uid} {
      // Own profile remains readable after deactivation so the client can close its session.
      allow get: if signedIn() && (request.auth.uid == uid || (can('users.view') && tenant(resource.data) && contract(resource.data)));
      allow list: if can('users.view') && tenant(resource.data) && contract(resource.data);
      allow create: if can('users.create') && tenant(request.resource.data) && validUser(request.resource.data, uid)
        && mayGrant(request.resource.data) && (can('access.manage') || request.resource.data.role == 'CLIENTE_VISUALIZADOR' && request.resource.data.permissions.size() == 0);
      allow update: if tenant(resource.data) && tenant(request.resource.data) && contract(resource.data)
        && validUser(request.resource.data, uid) && request.resource.data.email == resource.data.email
        && userUpdateAllowed(resource.data, request.resource.data, uid);
      allow delete: if can('users.delete') && tenant(resource.data) && contract(resource.data)
        && request.auth.uid != uid && resource.data.role != 'SUPER_ADMIN';
    }
    function validTemplate(data, id) {
      return can('access.profiles') && tenant(data)
        && data.keys().hasOnly(['id','name','tenantId','permissions']) && data.id == id
        && data.name is string && data.name.size() > 0 && validPermissions(data.permissions) && !('maintenance.reset' in data.permissions)
        && (principal() || (!('maintenance.reset' in data.permissions) && permissionsOf(member()).hasAll(data.permissions)));
    }
    match /permission_profiles/{id} {
      allow read: if can('access.view') && tenant(resource.data);
      allow create: if validTemplate(request.resource.data, id);
      allow update: if tenant(resource.data) && validTemplate(request.resource.data, id);
      allow delete: if can('access.profiles') && tenant(resource.data);
    }
    function immutableScope() {
      return request.resource.data.tenantId == resource.data.tenantId
        && request.resource.data.get('contractId', 'c1') == resource.data.get('contractId', 'c1');
    }
    function orderAligned(data) {
      return 'payload' in data && !data.payload.keys().hasAny(['hasBeforeEvidence','hasAfterEvidence']) && (data.payload.tenantId == data.tenantId && data.payload.get('contractId', 'c1') == data.get('contractId', 'c1') && data.payload.get('areaId', '') == data.get('areaId', '') && data.payload.status == data.status);
    }
    function protectedApprovalUnchanged() {
      return !payload(request.resource.data).diff(payload(resource.data)).affectedKeys().hasAny(${list(approvalFields)});
    }
    function validOrderUpdate() {
      let changed = payload(request.resource.data).diff(payload(resource.data)).affectedKeys();
      return (can('orders.edit') && protectedApprovalUnchanged()
          && (can('evidence.upload') || !changed.hasAny(${list(PHOTO_FIELDS)})))
        || (can('orders.edit') && !changed.hasAny(${list(approvalFields.filter(k => k !== 'status'))})
          && payload(resource.data).get('status', '') != 'APROBADO_MANDANTE'
          && payload(request.resource.data).get('status', '') != 'APROBADO_MANDANTE'
          && (can('evidence.upload') || !changed.hasAny(${list(PHOTO_FIELDS)})))
        || (can('orders.approve') && changed.hasOnly(${list([...approvalFields, ...trace])})
          && payload(request.resource.data).status == 'APROBADO_MANDANTE'
          && payload(request.resource.data).get('approvedById', request.auth.uid) == request.auth.uid)
        || (can('evidence.upload') && changed.hasOnly(${list([...PHOTO_FIELDS.filter(k => k !== 'itoSignatureDataUrl'), ...trace])}))
        || (can('reporting.assign') && changed.hasOnly(${list(['responsibleSupervisorId', 'responsibleSupervisorName', ...trace])}));
    }
    match /work_orders/{id} {
      allow read: if can('orders.view') && can('evidence.view') && scoped(resource.data);
      allow create: if can('orders.create') && scoped(request.resource.data) && orderAligned(request.resource.data) && projectionsAligned(id)
        && payload(request.resource.data).revision is string
        && payload(request.resource.data).status != 'APROBADO_MANDANTE'
        && !payload(request.resource.data).keys().hasAny(${list(approvalFields.filter(k => k !== 'status'))})
        && (can('evidence.upload') || !payload(request.resource.data).keys().hasAny(${list(PHOTO_FIELDS)}));
      allow update: if scoped(resource.data) && scoped(request.resource.data) && immutableScope() && orderAligned(request.resource.data) && projectionsAligned(id) && validOrderUpdate()
        && payload(request.resource.data).revision is string && payload(request.resource.data).revision != payload(resource.data).get('revision','')
        && request.resource.data.diff(resource.data).affectedKeys().hasOnly(['payload','status','staffingType','sapCode','equipoCorrea','tenantId','contractId','areaId','updatedAt']);
      allow delete: if can('orders.delete') && scoped(resource.data)
        && !existsAfter(/databases/$(database)/documents/work_order_details/$(id))
        && !existsAfter(/databases/$(database)/documents/work_order_metrics/$(id));
    }
    function sourceOrder(id) { return getAfter(/databases/$(database)/documents/work_orders/$(id)).data; }
    function mayWriteProjection() { let actor = member(); return signedIn() && actor.active == true && (actor.role == 'SUPER_ADMIN' || permissionsOf(actor).hasAny(['orders.create','orders.edit','orders.approve','evidence.upload','reporting.assign'])); }
    function photoPresent(source, key) { let value = source.get(key, ''); return value is string && value.size() > 0; }
    function validOrderProjection(id, metric) {
      let raw = getAfter(/databases/$(database)/documents/work_orders/$(id)).data;
      let source = raw.payload;
      let projected = request.resource.data;
      let before = photoPresent(source, 'imageBeforeUrl') || photoPresent(source, 'beforePhotoUrl');
      let after = photoPresent(source, 'imageAfterUrl') || photoPresent(source, 'afterPhotoUrl');
      return mayWriteProjection() && scoped(raw) && projected.id == id && projected.revision == source.revision
        && (metric
          ? projected.keys().hasOnly(${list([...METRIC_FIELDS, 'hasBeforeEvidence', 'hasAfterEvidence'])})
            && !projected.diff(source).removedKeys().hasAny(${list(METRIC_FIELDS)})
            && projected.diff(source).changedKeys().hasOnly(['hasBeforeEvidence','hasAfterEvidence'])
            && projected.diff(source).addedKeys().hasOnly(['hasBeforeEvidence','hasAfterEvidence'])
          : !projected.keys().hasAny(${list(PHOTO_FIELDS)})
            && source.diff(projected).affectedKeys().hasOnly(${list([...PHOTO_FIELDS, 'hasBeforeEvidence', 'hasAfterEvidence'])}))
        && projected.hasBeforeEvidence == before && projected.hasAfterEvidence == after;
    }
    function projectionsAligned(id) {
      let source = request.resource.data.payload;
      return source.id == id
        && getAfter(/databases/$(database)/documents/work_order_details/$(id)).data.revision == source.revision
        && getAfter(/databases/$(database)/documents/work_order_metrics/$(id)).data.revision == source.revision;
    }
    match /work_order_details/{id} {
      allow read: if can('orders.view') && scoped(resource.data);
      allow create, update: if validOrderProjection(id, false);
      allow delete: if can('orders.delete') && scoped(resource.data) && !existsAfter(/databases/$(database)/documents/work_orders/$(id));
    }
    match /work_order_metrics/{id} {
      allow read: if (can('kpi.view') || can('map.view') || can('orders.view')) && scoped(resource.data);
      allow create, update: if validOrderProjection(id, true);
      allow delete: if can('orders.delete') && scoped(resource.data) && !existsAfter(/databases/$(database)/documents/work_orders/$(id));
    }
    function canonical(data) { return !('payload' in data) || data.diff(data.payload).affectedKeys().hasOnly(['payload','updatedAt']); }
    match /proclean_dailyAssignments/{id} {
      allow read: if can('coverage.names') && tenant(resource.data) && contract(resource.data);
      allow create: if can('coverage.edit') && tenant(request.resource.data) && contract(request.resource.data) && canonical(request.resource.data);
      allow update: if can('coverage.edit') && tenant(resource.data) && contract(resource.data) && tenant(request.resource.data) && contract(request.resource.data) && immutableScope() && canonical(request.resource.data);
      allow delete: if can('coverage.edit') && tenant(resource.data) && contract(resource.data);
    }
    match /coverage_public/{id} {
      allow read: if can('coverage.view') && tenant(resource.data) && contract(resource.data);
      allow create, update: if can('coverage.edit') && tenant(request.resource.data) && contract(request.resource.data)
        && request.resource.data.keys().hasOnly(${list([...COVERAGE_FIELDS, 'personId', 'personName'])})
        && request.resource.data.personName == ''
        && request.resource.data.personId == (payload(getAfter(/databases/$(database)/documents/proclean_dailyAssignments/$(id)).data).personId != '' ? 'covered' : '')
        && request.resource.data.diff(payload(getAfter(/databases/$(database)/documents/proclean_dailyAssignments/$(id)).data)).affectedKeys().hasOnly(['personId','personName','personSource','userEmail','createdAt']);
      allow delete: if can('coverage.edit') && tenant(resource.data) && contract(resource.data) && !existsAfter(/databases/$(database)/documents/proclean_dailyAssignments/$(id));
    }
    function catalogRead(name) {
      return (name in ['plant_areas','sectors','equipments','sub_sectors'] && (can('structure.view') || can('orders.view') || can('map.view') || can('kpi.view')))
        || (name == 'machines' && (can('machines.view') || can('orders.view') || can('map.view')))
        || (name == 'workers' && can('workers.view')) || (name == 'proclean_personnel' && can('personnel.view'))
        || (name in ['proclean_coverageAreas','proclean_cargos'] && (can('coverage.view') || can('coverageConfig.view')))
        || name in ['contracts','shifts','whitelabel']
        || (name == 'contingencies' && (can('orders.create') || can('orders.edit') || can('contingencies.manage')));
    }
    function catalogWrite(name) {
      return (name in ['plant_areas','sectors','equipments','sub_sectors'] && can('structure.manage'))
        || (name == 'machines' && can('machines.manage')) || (name == 'workers' && can('workers.manage'))
        || (name == 'proclean_personnel' && can('personnel.manage'))
        || (name in ['proclean_coverageAreas','proclean_cargos'] && can('coverageConfig.manage'))
        || (name == 'contracts' && (can('contracts.manage') || can('branding.manage'))) || (name == 'shifts' && can('shifts.manage'))
        || (name == 'contingencies' && can('contingencies.manage')) || (name == 'whitelabel' && (can('branding.manage') || can('manualMatrix.manage')));
    }
    match /{name}/{id} {
      allow read: if name in ['plant_areas','sectors','equipments','sub_sectors','machines','workers','proclean_personnel','proclean_coverageAreas','proclean_cargos','contracts','shifts','whitelabel','contingencies'] && catalogRead(name) && tenant(resource.data) && (name != 'contracts' || contract(resource.data));
      allow create: if name in ['plant_areas','sectors','equipments','sub_sectors','machines','workers','proclean_personnel','proclean_coverageAreas','proclean_cargos','contracts','shifts','whitelabel','contingencies'] && catalogWrite(name) && tenant(request.resource.data) && (name != 'whitelabel' || can('branding.manage')) && (name != 'contracts' || can('contracts.manage')) && (name != 'contracts' || contract(request.resource.data));
      allow update: if name in ['plant_areas','sectors','equipments','sub_sectors','machines','workers','proclean_personnel','proclean_coverageAreas','proclean_cargos','contracts','shifts','whitelabel','contingencies'] && catalogWrite(name) && tenant(resource.data) && tenant(request.resource.data) && (name != 'contracts' || contract(resource.data) && contract(request.resource.data))
        && (name != 'contracts' || can('contracts.manage') || request.resource.data.diff(resource.data).affectedKeys().hasOnly(['payload','clientLogoUrl','updatedAt']) && payload(request.resource.data).diff(payload(resource.data)).affectedKeys().hasOnly(['clientLogoUrl']))
        && (name != 'whitelabel' || can('branding.manage') || request.resource.data.diff(resource.data).affectedKeys().hasOnly(['payload','manualLaborConfig','updatedAt']) && payload(request.resource.data).diff(payload(resource.data)).affectedKeys().hasOnly(['manualLaborConfig']));
      allow delete: if name in ['plant_areas','sectors','equipments','sub_sectors','machines','workers','proclean_personnel','proclean_coverageAreas','proclean_cargos','contracts','shifts','whitelabel','contingencies'] && catalogWrite(name) && tenant(resource.data) && (name != 'contracts' || can('contracts.manage') && contract(resource.data));
    }
    match /audit_logs/{id} {
      allow read: if can('audit.view') && tenant(resource.data) && contract(resource.data);
      allow create: if active() && tenant(request.resource.data);
      allow update, delete: if false;
    }
  }
}
`;
const target = new URL('../firestore.rules', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== rules) throw new Error('firestore.rules is stale; run npm run generate:rules');
} else await writeFile(target, rules);
